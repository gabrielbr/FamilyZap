#!/usr/bin/env python3
"""Oiê's design build: three layers in, OTokens.kt and tokens.css out (design/README.md).

    python3 design/build.py          # write design/generated/OTokens.kt and tokens.css
    python3 design/build.py --check  # the checks, and fail if the generated files aren't what the layers make

The layers:
  design/core/                 the Gabriel Design System's core, vendored at a pinned version
                               (core.json + its scripts, unchanged; see design/core/CORE.md)
  design/brand/oie/            the Oiê brand (brand.json): colour roles and the type family
  design/product/oie/          Oiê's own layer (layer.json): its tokens and contrast pairs

They are put together as the core's generator expects one tokens file, then the core's own code
writes Kotlin (compose_kt) and runs its checks (layers, brand limits, contrast in light and dark). So
Oiê never forks the generator: re-syncing the core is copying its files in.
"""
import json
import pathlib
import sys

DESIGN = pathlib.Path(__file__).resolve().parent
REPO = DESIGN.parent
sys.path.insert(0, str(DESIGN / "core" / "scripts"))

import check_tokens  # noqa: E402  (the core's checks)
import gen_tokens  # noqa: E402  (the core's generator)

OUT = {
    "kt": DESIGN / "generated" / "OTokens.kt",
    "app_kt": REPO / "app/src/main/java/app/oie/ui/theme/OTokens.kt",  # the app's copy, kept identical
    "css": DESIGN / "generated" / "tokens.css",
}
BRAND = "oie"
LAYER = "oie"


def read(path):
    return json.loads(path.read_text())


def assemble():
    """The three layers as one tokens document, the shape the core's scripts read."""
    core = read(DESIGN / "core" / "core.json")
    brand = read(DESIGN / "brand" / BRAND / "brand.json")
    product = read(DESIGN / "product" / LAYER / "layer.json")
    version = (DESIGN / "VERSION").read_text().strip()
    return {
        "name": "Oiê design",
        "version": f"{version} (core {core['version']})",
        "core": core["core"],
        "layers": {LAYER: product["layer"]},
        "brands": {k: v for k, v in brand.items() if not k.startswith("$")},
        "variants": {},
        "contrast": product["contrast"],
    }


def kotlin(t):
    # The core's Compose writer (gen_tokens.compose_kt), with a header that says where these
    # values come from.
    gen_tokens.HEADER = ("GENERATED by Oiê design/build.py from design/ (Gabriel Design System core + "
                         "Oiê brand + Oiê layer) v{v} — do not edit.")
    return gen_tokens.compose_kt(t, LAYER, "app.oie.ui.theme", "OTokens", [
        "Gabriel Design System values for Oiê. Screens read colours through OieTheme.colors,",
        "which picks Light or Dark; sizes are dp, type sizes sp, durations ms.",
    ])


def outputs(t):
    kt = kotlin(t)
    return {"kt": kt, "app_kt": kt, "css": gen_tokens.css(t, LAYER)}


def checks(t):
    check_tokens.check_layers(t)
    check_tokens.check_brands(t)
    check_tokens.check_contrast(t)
    return check_tokens.errors, check_tokens.warnings


def main():
    t = assemble()
    errors, warnings = checks(t)
    for w in warnings:
        print("warning:", w)
    for e in errors:
        print("error:", e)
    made = outputs(t)
    if "--check" in sys.argv:
        for key, path in OUT.items():
            if not path.exists() or path.read_text() != made[key]:
                errors.append(f"{path.relative_to(REPO)} differs from what design/ makes: run python3 design/build.py")
                print("error:", errors[-1])
        print("design check:", "failed" if errors else "ok", f"({len(errors)} error(s), {len(warnings)} warning(s))")
        return 1 if errors else 0
    if errors:
        print("not written: fix the errors first")
        return 1
    for key, path in OUT.items():
        if not path.exists() or path.read_text() != made[key]:
            path.write_text(made[key])
            print("wrote", path.relative_to(REPO))
        else:
            print(path.name, "is up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
