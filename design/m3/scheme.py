#!/usr/bin/env python3
"""Oiê's Material 3 colour scheme, from the brand coral as the seed (decision 0018).

Material's own colour algorithm (the materialyoucolor port of Google's material-color-utilities),
"Fidelity" scheme, which keeps the seed's colour (Material Theme Builder's "Color match"), 2025 spec.

    python3 -m pip install materialyoucolor==3.0.4   # once, a build-time tool only (not in the app)
    python3 design/m3/scheme.py                      # writes design/generated/OieScheme.kt and the app's copy
    python3 design/m3/scheme.py --check              # fails if the copies are stale; prints contrast

Never edit the generated file; change SEED or SCHEME here and run it again.
"""
import sys, pathlib, json
from materialyoucolor.hct import Hct
from materialyoucolor.scheme.scheme_fidelity import SchemeFidelity
from materialyoucolor.dynamiccolor.material_dynamic_colors import MaterialDynamicColors as M

SEED = 0xFFE8573C          # the brand coral (design/brand/oie/brand.json)
SPEC = "2025"
ROLES = [
    "primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "inversePrimary",
    "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
    "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
    "background", "onBackground", "surface", "onSurface", "surfaceVariant", "onSurfaceVariant",
    "surfaceTint", "inverseSurface", "inverseOnSurface",
    "error", "onError", "errorContainer", "onErrorContainer",
    "outline", "outlineVariant", "scrim",
    "surfaceBright", "surfaceContainer", "surfaceContainerHigh", "surfaceContainerHighest",
    "surfaceContainerLow", "surfaceContainerLowest", "surfaceDim",
]
ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = [ROOT / "design/generated/OieScheme.kt", ROOT / "app/src/main/java/app/oie/ui/theme/OieScheme.kt"]


def scheme(dark):
    s = SchemeFidelity(Hct.from_int(SEED), dark, 0.0, spec_version=SPEC)
    return {r: getattr(M, r).get_argb(s) & 0xFFFFFFFF for r in ROLES}


def lum(c):
    def ch(v):
        v /= 255
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = (c >> 16) & 255, (c >> 8) & 255, c & 255
    return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b)


def ratio(a, b):
    la, lb = sorted([lum(a), lum(b)], reverse=True)
    return (la + 0.05) / (lb + 0.05)


# The text pairs the screens use: every one must reach 4.5:1 in both themes.
PAIRS = [
    ("onPrimary", "primary"), ("onPrimaryContainer", "primaryContainer"),
    ("onSecondaryContainer", "secondaryContainer"), ("onTertiaryContainer", "tertiaryContainer"),
    ("onSurface", "surface"), ("onSurfaceVariant", "surface"), ("onSurface", "surfaceContainer"),
    ("onSurfaceVariant", "surfaceContainer"), ("onSurface", "surfaceContainerHigh"),
    ("onSurfaceVariant", "surfaceContainerHigh"), ("onSurface", "surfaceContainerHighest"),
    ("onSurfaceVariant", "surfaceContainerHighest"), ("primary", "surface"), ("primary", "surfaceContainer"),
    ("onErrorContainer", "errorContainer"), ("onError", "error"), ("error", "surface"),
    ("inverseOnSurface", "inverseSurface"),
]
# Graphics and boundaries: 3:1.
GRAPHIC = [("outline", "surface"), ("primary", "surface")]


def kotlin(light, dark):
    def block(name, fn, s):
        body = ",\n".join(f"    {r} = Color(0x{s[r]:08X})" for r in ROLES)
        return f"val {name} = {fn}(\n{body},\n)\n"
    return (
        "// GENERATED by design/m3/scheme.py from the brand coral (#E8573C), Material's Fidelity scheme,\n"
        "// 2025 spec (decision 0018). Never edit; run the script again.\n"
        "package app.oie.ui.theme\n\n"
        "import androidx.compose.material3.darkColorScheme\n"
        "import androidx.compose.material3.lightColorScheme\n"
        "import androidx.compose.ui.graphics.Color\n\n"
        + block("OieLightScheme", "lightColorScheme", light) + "\n"
        + block("OieDarkScheme", "darkColorScheme", dark)
    )


def main():
    light, dark = scheme(False), scheme(True)
    text = kotlin(light, dark)
    bad = []
    for theme, s in (("light", light), ("dark", dark)):
        for fg, bg in PAIRS:
            r = ratio(s[fg], s[bg])
            if r < 4.5: bad.append(f"{theme}: {fg} on {bg} {r:.2f}:1 (text needs 4.5)")
        for fg, bg in GRAPHIC:
            r = ratio(s[fg], s[bg])
            if r < 3: bad.append(f"{theme}: {fg} on {bg} {r:.2f}:1 (graphics need 3)")
    if "--check" in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p in OUT if not p.exists() or p.read_text() != text]
        if stale: print("stale:", ", ".join(stale)); sys.exit(1)
    else:
        for p in OUT: p.write_text(text)
    for b in bad: print("contrast:", b)
    print(f"scheme: {len(ROLES)} roles x 2 themes; contrast {'ok' if not bad else 'FAILS'}")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
